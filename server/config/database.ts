let memoryCache: HotelDatabase | null = null;

function ensureDbFile(): void {
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
  if (!fs.existsSync(DB_FILE)) {
    const initial = createInitialSeed();
    fs.writeFileSync(DB_FILE, JSON.stringify(initial, null, 2), 'utf-8');
    memoryCache = initial;
  }
}

export function readDb(): HotelDatabase {
  if (memoryCache) {
    return memoryCache;
  }
  ensureDbFile();
  const raw = fs.readFileSync(DB_FILE, 'utf-8');
  const parsed = JSON.parse(raw) as Partial<HotelDatabase>;
  if (
    !Array.isArray(parsed.hotels) ||
    !Array.isArray(parsed.messages) ||
    !Array.isArray(parsed.taskReports) ||
    !Array.isArray(parsed.customers) ||
    !Array.isArray(parsed.inquiries) ||
    !Array.isArray(parsed.fbMenu) ||
    !Array.isArray(parsed.fbOrders) ||
    !Array.isArray(parsed.tables) ||
    !parsed.users?.some((u) => u.role === 'waiter') ||
    parsed.hotels.some((h) => typeof (h as HotelProperty).starRating !== 'number')
  ) {
    const seeded = createInitialSeed();
    fs.writeFileSync(DB_FILE, JSON.stringify(seeded, null, 2), 'utf-8');
    memoryCache = seeded;
    return memoryCache;
  }
  let brandMigrated = false;
  for (const h of parsed.hotels as HotelProperty[]) {
    if (h.name?.includes('Zema')) {
      h.name = h.name.replace(/Zema/g, 'Tekno');
      brandMigrated = true;
    }
    if (h.amharicName?.includes('ዜማ')) {
      h.amharicName = h.amharicName.replace(/ዜማ/g, 'ቴክኖ');
      brandMigrated = true;
    }
    if (h.email?.includes('zemahotels.et')) {
      h.email = h.email.replace(/zemahotels\.et/g, 'teknohotels.et');
      brandMigrated = true;
    }
    if (h.code?.startsWith('ZMA-')) {
      h.code = h.code.replace(/^ZMA-/, 'TKN-');
      brandMigrated = true;
    }
  }
  if (!parsed.users?.some((u) => u.id === 'central-admin-1' && u.hotelId === 'central')) {
    parsed.users = [
      {
        id: 'central-admin-1',
        hotelId: 'central',
        name: 'Kal Tekno Central Admin',
        amharicName: 'ቃል ቴክኖ ዋና አድሚን',
        role: 'manager',
        departmentLabel: 'ቃል ቴክኖ ዋና ሰርቨር (Central HQ)',
        shift: 'Central Server Super Admin',
        pinCode: '9999',
      },
      ...(parsed.users || []),
    ];
    brandMigrated = true;
  }

  // Ensure every hotel property has a dedicated Cashier user (PIN 9090) and synchronized Order/Payment fields
  for (const h of parsed.hotels as HotelProperty[]) {
    const hasCashier = parsed.users?.some((u) => u.hotelId === h.id && u.role === 'cashier');
    if (!hasCashier) {
      const prefix = h.id.replace(/^htl-/, '').slice(0, 6);
      parsed.users = [
        ...(parsed.users || []),
        {
          id: `${prefix}-csh-1`,
          hotelId: h.id,
          name: 'Rahel Teshome',
          amharicName: 'ራሄል ተሾመ',
          role: 'cashier',
          departmentLabel: 'Cashier & Billing Counter',
          shift: 'Cashier Desk (08:00–20:00)',
          pinCode: '9090',
        },
      ];
      brandMigrated = true;
    }
  }

  for (const ord of parsed.fbOrders as FbOrder[]) {
    if (!ord.billStatus) {
      ord.billStatus = ord.isPaid
        ? 'Paid'
        : ord.settlementMode === 'Charge to Room'
          ? 'Charged to Room'
          : 'Open Tab';
      brandMigrated = true;
    }
  }

  for (const pay of parsed.payments as ManualPayment[]) {
    if (!pay.sourceType) {
      pay.sourceType =
        pay.bookingId === 'walk-in-table' || pay.bookingId === 'walk-in-fb'
          ? 'Table / F&B Order'
          : 'Room Booking';
      brandMigrated = true;
    }
    if (!pay.verificationStatus) {
      pay.verificationStatus = 'Verified';
      brandMigrated = true;
    }
  }

  if (brandMigrated) {
    fs.writeFileSync(DB_FILE, JSON.stringify(parsed, null, 2), 'utf-8');
  }
  memoryCache = parsed as HotelDatabase;
  return memoryCache;
}

export function writeDb(nextDb: HotelDatabase): void {
  ensureDbFile();
  memoryCache = nextDb;
  fs.writeFileSync(DB_FILE, JSON.stringify(nextDb, null, 2), 'utf-8');
}
